#!/usr/bin/env python3
"""Generate the photo album manifest from folders in site/assets/Photos."""

from __future__ import annotations

import json
from pathlib import Path
from urllib.parse import quote


ROOT = Path(__file__).resolve().parents[1]
PHOTOS_DIR = ROOT / "site" / "assets" / "Photos"
OUTPUT = ROOT / "site" / "photo-albums.js"
IMAGE_EXTENSIONS = {
    ".avif",
    ".bmp",
    ".gif",
    ".jpeg",
    ".jpg",
    ".png",
    ".svg",
    ".webp",
}


def natural_key(path: Path) -> tuple[object, ...]:
    """Sort names naturally while retaining their original spelling."""
    import re

    return tuple(
        int(part) if part.isdigit() else part.casefold()
        for part in re.split(r"(\d+)", path.name)
    )


def web_path(album_name: str, image_name: str) -> str:
    return "assets/Photos/{}/{}".format(
        quote(album_name, safe=""),
        quote(image_name, safe=""),
    )


def build_albums() -> list[dict[str, object]]:
    PHOTOS_DIR.mkdir(parents=True, exist_ok=True)
    albums: list[dict[str, object]] = []

    for folder in sorted((path for path in PHOTOS_DIR.iterdir() if path.is_dir()), key=natural_key):
        images = sorted(
            (
                path
                for path in folder.iterdir()
                if path.is_file() and path.suffix.casefold() in IMAGE_EXTENSIONS
            ),
            key=natural_key,
        )
        albums.append(
            {
                "id": "album:" + folder.name,
                "name": folder.name,
                "photos": [
                    {
                        "src": web_path(folder.name, image.name),
                        "alt": image.stem,
                        "caption": image.name,
                    }
                    for image in images
                ],
            }
        )

    return albums


def main() -> None:
    albums = build_albums()
    payload = json.dumps(albums, ensure_ascii=False, indent=2)
    OUTPUT.write_text(
        "/* Generated by tools/generate_photo_albums.py. Do not edit by hand. */\n"
        f"window.portfolioPhotoAlbums = {payload};\n",
        encoding="utf-8",
    )
    image_count = sum(len(album["photos"]) for album in albums)
    print(f"Generated {len(albums)} photo album(s) with {image_count} image(s).")


if __name__ == "__main__":
    main()
