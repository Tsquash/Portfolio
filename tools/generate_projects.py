#!/usr/bin/env python3
"""Generate the project manifest from Markdown files in site/assets/Projects."""

from __future__ import annotations

import json
import re
from pathlib import Path
from urllib.parse import quote


ROOT = Path(__file__).resolve().parents[1]
PROJECTS_DIR = ROOT / "site" / "assets" / "Projects"
OUTPUT = ROOT / "site" / "projects.js"
TITLE = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)


def natural_key(path: Path) -> list[object]:
    return [
        int(part) if part.isdigit() else part.casefold()
        for part in re.split(r"(\d+)", path.name)
    ]


def build_projects() -> list[dict[str, str]]:
    PROJECTS_DIR.mkdir(parents=True, exist_ok=True)
    projects: list[dict[str, str]] = []

    for folder in sorted((path for path in PROJECTS_DIR.iterdir() if path.is_dir()), key=natural_key):
        markdown_files = sorted(folder.glob("*.md"), key=natural_key)
        if len(markdown_files) != 1:
            raise ValueError(f"{folder.relative_to(ROOT)} must contain exactly one .md file")

        markdown_file = markdown_files[0]
        markdown = markdown_file.read_text(encoding="utf-8")
        title = TITLE.search(markdown)
        if not title:
            raise ValueError(f"{markdown_file.relative_to(ROOT)} must begin a line with a level-one heading")

        projects.append(
            {
                "id": "project:" + folder.name,
                "name": title.group(1),
                "markdown": markdown,
                "assetBase": "assets/Projects/" + quote(folder.name, safe=""),
            }
        )

    return projects


def main() -> None:
    projects = build_projects()
    payload = json.dumps(projects, ensure_ascii=False, indent=2)
    OUTPUT.write_text(
        "/* Generated by tools/generate_projects.py. Do not edit by hand. */\n"
        f"window.portfolioProjects = {payload};\n",
        encoding="utf-8",
    )
    print(f"Generated {len(projects)} project(s).")


if __name__ == "__main__":
    main()
